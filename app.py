@app.route("/admin/unlock", methods=["POST"])
def admin_unlock():

    data = get_request_data()

    code = str(data.get("code", ""))

    if not ADMIN_ACCESS_CODE:
        return jsonify({
            "success": False,
            "message": "رمز الإدارة غير مضبوط"
        }), 500

    if not hmac.compare_digest(
        code,
        ADMIN_ACCESS_CODE
    ):

        return jsonify({
            "success": False,
            "message": "رمز الإدارة غير صحيح"
        }), 403

    session["admin_access"] = True

    return jsonify({
        "success": True,
        "message": "تم فتح لوحة الإدارة",
        "redirect": "/admin"
    })


