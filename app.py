@app.route(
    "/api/shorts/<int:short_id>/comments",
    methods=["GET", "POST"]
)
def api_comments(short_id):

    if request.method == "GET":

        with get_db() as conn:

            comments = conn.execute("""
                SELECT
                    c.id,
                    c.short_id,
                    c.user_id,
                    c.parent_id,
                    c.content,
                    c.created_at,
                    u.username
                FROM public.comments c
                JOIN public.users u ON u.id = c.user_id
                JOIN public.shorts s ON s.id = c.short_id
                WHERE c.short_id = %s
                  AND s.status = 'approved'
                ORDER BY c.created_at ASC
            """, (short_id,)).fetchall()

        return jsonify({
            "success": True,
            "comments": comments
        })

    user = current_user()

    if not user:
        return jsonify({
            "success": False,
            "message": "يجب تسجيل الدخول"
        }), 401

    data = get_request_data()

    content = str(data.get("content", "")).strip()
    parent_id = data.get("parent_id")

    if not content:
        return jsonify({
            "success": False,
            "message": "التعليق فارغ"
        }), 400

    with get_db() as conn:

        short = conn.execute("""
            SELECT id
            FROM public.shorts
            WHERE id = %s AND status = 'approved'
        """, (short_id,)).fetchone()

        if not short:
            return jsonify({
                "success": False,
                "message": "المقطع غير موجود"
            }), 404

        if parent_id:

            parent = conn.execute("""
                SELECT id
                FROM public.comments
                WHERE id = %s AND short_id = %s
            """, (
                parent_id,
                short_id
            )).fetchone()

            if not parent:
                return jsonify({
                    "success": False,
                    "message": "التعليق الأصلي غير موجود"
                }), 400

        comment = conn.execute("""
            INSERT INTO public.comments
            (
                short_id,
                user_id,
                parent_id,
                content
            )
            VALUES (%s, %s, %s, %s)
            RETURNING id, created_at
        """, (
            short_id,
            user["id"],
            parent_id,
            content
        )).fetchone()

    return jsonify({
        "success": True,
        "message": "تم نشر التعليق",
        "comment": {
            "id": comment["id"],
            "short_id": short_id,
            "user_id": user["id"],
            "username": user["username"],
            "parent_id": parent_id,
            "content": content,
            "created_at": comment["created_at"]
        }
    })


