def init_database():

    with get_db() as conn:

        conn.execute("""
            CREATE TABLE IF NOT EXISTS public.users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT UNIQUE NOT NULL,
                password TEXT NOT NULL,
                is_admin BOOLEAN DEFAULT FALSE,
                created_at TIMESTAMPTZ DEFAULT NOW()
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS public.shorts (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL
                    REFERENCES public.users(id) ON DELETE CASCADE,
                title TEXT NOT NULL,
                video_url TEXT NOT NULL,
                description TEXT DEFAULT '',
                status TEXT DEFAULT 'pending',
                created_at TIMESTAMPTZ DEFAULT NOW()
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS public.comments (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                short_id BIGINT NOT NULL
                    REFERENCES public.shorts(id) ON DELETE CASCADE,
                user_id BIGINT NOT NULL
                    REFERENCES public.users(id) ON DELETE CASCADE,
                parent_id BIGINT
                    REFERENCES public.comments(id) ON DELETE CASCADE,
                content TEXT NOT NULL,
                created_at TIMESTAMPTZ DEFAULT NOW()
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS public.likes (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                short_id BIGINT NOT NULL
                    REFERENCES public.shorts(id) ON DELETE CASCADE,
                user_id BIGINT NOT NULL
                    REFERENCES public.users(id) ON DELETE CASCADE,
                created_at TIMESTAMPTZ DEFAULT NOW(),
                UNIQUE(short_id, user_id)
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS public.migration_tracking (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                migration_name TEXT UNIQUE NOT NULL,
                completed_at TIMESTAMPTZ DEFAULT NOW()
            )
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_shorts_status
            ON public.shorts(status)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_comments_short_id
            ON public.comments(short_id)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_likes_short_id
            ON public.likes(short_id)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_likes_user_id
            ON public.likes(user_id)
        """)


