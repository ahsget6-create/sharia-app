def has_admin_access():

    user = current_user()

    return (
        session.get("admin_access", False)
        or (user is not None and user["is_admin"])
    )


def login_required(func):

    @wraps(func)
    def wrapper(*args, **kwargs):

        if not current_user():
            return jsonify({
                "success": False,
                "message": "يجب تسجيل الدخول أولاً"
            }), 401

        return func(*args, **kwargs)

    return wrapper


def admin_required(func):

    @wraps(func)
    def wrapper(*args, **kwargs):

        if not has_admin_access():
            return jsonify({
                "success": False,
                "message": "ليس لديك صلاحية الإدارة"
            }), 403

        return func(*args, **kwargs)

    return wrapper


