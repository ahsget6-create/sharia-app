@app.route("/api/shorts", methods=["GET", "POST"])
def api_shorts():

    if request.method == "GET":

        with get_db() as conn:

            shorts = conn.execute("""
                SELECT
                    s.id,
                    s.user_id,
                    s.title,
                    s.video_url,
                    s.description,
                    s.status,
                    s.created_at,
                    u.username,
                    COUNT(DISTINCT l.id) AS likes_count,
                    COUNT(DISTINCT c.id) AS comments_count
                FROM public.shorts s
                JOIN public.users u ON u.id = s.user_id
                LEFT JOIN public.likes l ON l.short_id = s.id
                LEFT JOIN public.comments c ON c.short_id = s.id
                WHERE s.status = 'approved'
                GROUP BY s.id, u.username
                ORDER BY s.created_at DESC
            """).fetchall()

        return jsonify({
            "success": True,
            "shorts": shorts
        })

    user = current_user()

    if not user:
        return jsonify({
            "success": False,
            "message": "يجب تسجيل الدخول"
        }), 401

    data = get_request_data()

    title = str(data.get("title", "")).strip()
    video_url = str(data.get("video_url", "")).strip()
    description = str(data.get("description", "")).strip()

    if not title:
        return jsonify({
            "success": False,
            "message": "يرجى كتابة عنوان المقطع"
        }), 400

    if not valid_video_url(video_url):
        return jsonify({
            "success": False,
            "message": "رابط الفيديو غير صحيح"
        }), 400

    with get_db() as conn:

        short = conn.execute("""
            INSERT INTO public.shorts
            (
                user_id,
                title,
                video_url,
                description,
                status
            )
            VALUES (%s, %s, %s, %s, 'pending')
            RETURNING id
        """, (
            user["id"],
            title,
            video_url,
            description
        )).fetchone()

    return jsonify({
        "success": True,
        "message": "تم إرسال المقطع للمراجعة",
        "id": short["id"]
    })


