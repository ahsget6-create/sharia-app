@contextmanager
def get_db():

    conn = psycopg.connect(
        DATABASE_URL,
        sslmode="require",
        row_factory=dict_row
    )

    try:
        yield conn
        conn.commit()

    except Exception:
        conn.rollback()
        raise

    finally:
        conn.close()


