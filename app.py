def current_user():

    user_id = session.get("user_id")

    if not user_id:
        return None

    with get_db() as conn:

        return conn.execute("""
            SELECT id, username, is_admin
            FROM public.users
            WHERE id = %s
        """, (user_id,)).fetchone()


