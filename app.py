def migrate_old_database():

    if not DATABASE_PATH.exists():
        print("لم يتم العثور على قاعدة SQLite القديمة.")
        return

    migration_name = "sqlite_to_supabase_v1"

    with get_db() as conn:

        existing = conn.execute("""
            SELECT id
            FROM public.migration_tracking
            WHERE migration_name = %s
        """, (migration_name,)).fetchone()

        if existing:
            print("تم ترحيل قاعدة SQLite سابقاً.")
            return

        sqlite_conn = sqlite3.connect(DATABASE_PATH)
        sqlite_conn.row_factory = sqlite3.Row

        try:

            tables = {
                row["name"]
                for row in sqlite_conn.execute("""
                    SELECT name FROM sqlite_master
                    WHERE type = 'table'
                """).fetchall()
            }

            # نقل المستخدمين
            if "users" in tables:

                users = sqlite_conn.execute("""
                    SELECT * FROM users
                """).fetchall()

                for user in users:

                    conn.execute("""
                        INSERT INTO public.users
                        (id, username, password, is_admin, created_at)
                        VALUES (%s, %s, %s, %s, %s)
                        ON CONFLICT (id) DO NOTHING
                    """, (
                        user["id"],
                        user["username"],
                        user["password"],
                        bool(user["is_admin"]),
                        user["created_at"]
                    ))

                print(f"تم نقل {len(users)} حساب.")

            # نقل المقاطع
            if "shorts" in tables:

                shorts = sqlite_conn.execute("""
                    SELECT * FROM shorts
                """).fetchall()

                for short in shorts:

                    conn.execute("""
                        INSERT INTO public.shorts
                        (
                            id,
                            user_id,
                            title,
                            video_url,
                            description,
                            status,
                            created_at
                        )
                        VALUES (%s, %s, %s, %s, %s, %s, %s)
                        ON CONFLICT (id) DO NOTHING
                    """, (
                        short["id"],
                        short["user_id"],
                        short["title"],
                        short["video_url"],
                        short["description"],
                        short["status"],
                        short["created_at"]
                    ))

                print(f"تم نقل {len(shorts)} مقطع.")

            # نقل التعليقات والردود
            if "comments" in tables:

                comments = sqlite_conn.execute("""
                    SELECT * FROM comments
                """).fetchall()

                for comment in comments:

                    conn.execute("""
                        INSERT INTO public.comments
                        (
                            id,
                            short_id,
                            user_id,
                            parent_id,
                            content,
                            created_at
                        )
                        VALUES (%s, %s, %s, %s, %s, %s)
                        ON CONFLICT (id) DO NOTHING
                    """, (
                        comment["id"],
                        comment["short_id"],
                        comment["user_id"],
                        comment["parent_id"],
                        comment["content"],
                        comment["created_at"]
                    ))

                print(f"تم نقل {len(comments)} تعليق.")

            # ضبط أرقام التسلسل بعد نقل المعرفات القديمة
            for table in ("users", "shorts", "comments", "likes"):

                conn.execute(f"""
                    SELECT setval(
                        pg_get_serial_sequence(
                            'public.{table}', 'id'
                        ),
                        GREATEST(
                            COALESCE(
                                (SELECT MAX(id) FROM public.{table}),
                                1
                            ),
                            1
                        ),
                        EXISTS(
                            SELECT 1 FROM public.{table}
                        )
                    )
                """)

            conn.execute("""
                INSERT INTO public.migration_tracking
                (migration_name)
                VALUES (%s)
            """, (migration_name,))

            print("اكتمل ترحيل البيانات بنجاح.")

        finally:
            sqlite_conn.close()


